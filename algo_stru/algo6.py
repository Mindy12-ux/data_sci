# 버블 정렬 : 인접한 두 개의 원소를 비교하여 자리를 교환하는 방식의 가장 단순한 알고리즘

# 동작 방식
# 인접 원소 비교 : 배열의 첫 번째 원소부터 시작해 바로 옆의 원소가 값을 비교한다.
# 자리 교환 : 순서가 잘못되어 있다면 두 원소의 위치를 서로 바꾼다.
# 이 과정을 끝까지 반복하면 가장 큰 원소가 배열의 맨 마지막 자리로 이동한다.
# 맨 마지막으로 이동한 원소를 정렬이 완료된 것으로 간주하고 다음 회전에서는 제외한다. 전체 원소 수만큼 회전을 반복

def bubble_sort(a):
    n = len(a)
    while True:
        change = False  # flag 변수, 자료 앞뒤 변경 여부를 확인

        for i in range(0, n - 1):
            if a[i] > a[i + 1]:     # 앞이 뒤보다 크면
                a[i], a[i + 1] = a[i + 1], a[i]
                change = True   # 교환이 발생

        if change == False:
            return 

d = [2,4,5,1,3]
bubble_sort(d)
print(d)

